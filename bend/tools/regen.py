# regen.py : rewrites fuzz.bend's generated St region from st.py
import os, subprocess
here = os.path.dirname(os.path.abspath(__file__))
p = os.path.join(here, "..", "fuzz.bend")
s = open(p).read()
gen = subprocess.run(["python3", os.path.join(here, "st.py")], capture_output=True, text=True, check=True).stdout
a = s.index("# BEGIN St (generated by tools/st.py)\n") + len("# BEGIN St (generated by tools/st.py)\n")
b = s.index("# END St")
open(p, "w").write(s[:a] + gen + s[b:])
