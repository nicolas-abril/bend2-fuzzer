# table.py : writes fuzz.bend's BASE_TABLE from fuzz.ts's (one redefinition
# of Base, carried by both fuzzers)
import os, re
here = os.path.dirname(os.path.abspath(__file__))
ts = open(os.path.join(here, "..", "..", "fuzz.ts")).read()
table = re.search(r"const BASE_TABLE = `\n(.*?)\n`;", ts, re.S).group(1)
# one literal per line: a single literal of the whole table overflows the
# compiler's stack (a string literal expands to one nested chain)
lines = ['"' + l.replace("\\", "\\\\").replace('"', '\\"') + '"' for l in table.split("\n")]
p = os.path.join(here, "..", "fuzz.bend")
s = open(p).read()
begin, end = "# BEGIN BASE_TABLE (generated by tools/table.py)\n", "# END BASE_TABLE"
a = s.index(begin) + len(begin)
b = s.index(end)
open(p, "w").write(s[:a] + "def BASE_TABLE?() -> List<&2, String>:\n  [\n    " + ",\n    ".join(lines) + "\n  ]\n\n" + s[b:])
